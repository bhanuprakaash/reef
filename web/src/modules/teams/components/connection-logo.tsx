const tileColors = ['bg-lead', 'bg-architect', 'bg-developer', 'bg-tester'];

function tileColor(name: string) {
  let sum = 0;
  for (const ch of name) sum += ch.charCodeAt(0);
  return tileColors[sum % tileColors.length];
}

export function ConnectionLogo({ name, entryId }: { name: string; entryId?: string }) {
  const logo = logos[entryId ?? ''];
  if (logo) {
    return (
      <span className="flex size-[30px] flex-none items-center justify-center rounded-field border border-line bg-card">
        <svg viewBox={logo.viewBox ?? '0 0 24 24'} className="size-[17px]" aria-hidden="true">
          <path fill={logo.color ?? 'currentColor'} d={logo.path} />
          {logo.extra?.map((part) => (
            <path key={part.color} fill={part.color} d={part.path} />
          ))}
        </svg>
      </span>
    );
  }
  return (
    <span
      aria-hidden="true"
      className={`flex size-[30px] flex-none items-center justify-center rounded-field text-[13px] font-medium text-mark-ink uppercase ${tileColor(name)}`}
    >
      {name.charAt(0)}
    </span>
  );
}
